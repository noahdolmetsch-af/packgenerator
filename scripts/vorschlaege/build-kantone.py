#!/usr/bin/env python3
"""
«Tourenvorschläge» map (Noah 23.11.2026 «die karte unbedingt 1:1 so übernehmen»): builds src/lib/vorschlaege/data/kantone.js,
the 26 cantons as simplified SVG outlines in a 1440 × 900 frame (LV95: E 2480000 to 2840000, N 1070000 to 1300000, the same scale
on both axes). Source: swissBOUNDARIES3D (© swisstopo, open government data) through api3.geo.admin.ch (one point inside each canton).

  python3 -I scripts/vorschlaege/build-kantone.py > src/lib/vorschlaege/data/kantone.js

Only the standard library is used. The tours are drawn with the same frame (src/lib/vorschlaege/karte.js turns lat/lon into it).
"""
import json, urllib.request

W, H = 1440, 900
E0, N1 = 2480000, 1070000
SCALE = min(W / 360000, H / 230000)
STRIDE = 20
POINTS = {
    'ZH': (2683000, 1248000), 'BE': (2600000, 1200000), 'LU': (2665000, 1215000), 'UR': (2690000, 1180000), 'SZ': (2700000, 1215000),
    'OW': (2660000, 1190000), 'NW': (2670000, 1195000), 'GL': (2723000, 1205000), 'ZG': (2680000, 1225000), 'FR': (2575000, 1180000),
    'SO': (2610000, 1235000), 'BS': (2611000, 1267000), 'BL': (2625000, 1255000), 'SH': (2690000, 1288000), 'AR': (2740000, 1250000),
    'AI': (2752000, 1244000), 'SG': (2735000, 1232000), 'GR': (2760000, 1170000), 'AG': (2655000, 1245000), 'TG': (2720000, 1268000),
    'TI': (2710000, 1130000), 'VD': (2540000, 1170000), 'VS': (2620000, 1110000), 'NE': (2555000, 1205000), 'GE': (2500000, 1118000),
    'JU': (2575000, 1245000),
}


def xy(e, n):
    return round((e - E0) * SCALE, 1), round(H - (n - N1) * SCALE, 1)


out, labels = {}, {}
for ak, (e, n) in POINTS.items():
    url = ('https://api3.geo.admin.ch/rest/services/api/MapServer/identify?geometry=%d,%d&geometryType=esriGeometryPoint'
           '&layers=all:ch.swisstopo.swissboundaries3d-kanton-flaeche.fill&tolerance=0&mapExtent=%d,%d,%d,%d'
           '&imageDisplay=100,100,96&returnGeometry=true&geometryFormat=geojson&sr=2056') % (e, n, e - 1000, n - 1000, e + 1000, n + 1000)
    res = json.load(urllib.request.urlopen(url, timeout=60))['results']
    hit = [r for r in res if r['properties']['ak'] == ak]
    if not hit:
        raise SystemExit('no outline for %s: the point %d,%d lies in %s' % (ak, e, n, [r['properties']['ak'] for r in res]))
    g = hit[0]['geometry']
    polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    d, pts = '', []
    for poly in polys:
        for ring in poly:
            r = ring[::STRIDE] + [ring[-1]]
            p = [xy(a, b) for a, b in r]
            pts += p
            d += 'M' + 'L'.join('%s %s' % q for q in p) + 'Z'
    out[ak.lower()] = d
    # the label sits at the middle of the biggest outline's box
    big = max(polys, key=lambda pl: len(pl[0]))[0]
    xs, ys = [xy(a, b) for a, b in big[::STRIDE]], None
    labels[ak.lower()] = [round(sum(p[0] for p in xs) / len(xs), 1), round(sum(p[1] for p in xs) / len(xs), 1)]
print('// Generated by scripts/vorschlaege/build-kantone.py from swissBOUNDARIES3D (© swisstopo). Do not edit by hand.')
print('export default ' + json.dumps({'w': W, 'h': H, 'paths': out, 'labels': labels}, separators=(',', ':')) + ';')
