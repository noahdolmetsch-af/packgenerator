#!/usr/bin/env node
/**
 * Benutzerhandbuch (Noah 14.10.2026): writes docs/handbuch.md in German from the one source in the
 * code: the functions (src/lib/features.js, tips from tips.js) and how to use them
 * (src/lib/handbook.js), with the German texts of src/lib/i18n/de/.
 *
 *   node tools/handbuch.mjs
 *
 * features.js reaches i18n.svelte.js (through tips.js), which uses the Svelte rune $state: outside
 * Svelte a plain stand-in is enough here, the language is never switched.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

globalThis.$state ??= (v) => v;

const src = (p) => new URL(`../src/lib/${p}`, import.meta.url).href;
const { FEATURES, FEATURE_GROUPS } = await import(src('features.js'));
const { HANDBOOK, MINI_APPS_HANDBOOK } = await import(src('handbook.js'));
const DE = { ...(await import(src('i18n/de/index.js'))).default, ...(await import(src('i18n/de/handbuch.js'))).default };

/** The German text, like t(): without an entry the English one without its «|context». */
const de = (en) => DE[en] ?? String(en).replace(/\|[a-z]+$/, '');
/** «Beispiel: …» without its own word (the line says it), starting with a capital. */
const example = (en) => de(en).replace(/^Beispiel:\s*/, '').replace(/^./, (c) => c.toUpperCase());
const steps = (list) => list.map((s, i) => `${i + 1}. ${de(s)}`);

const out = [
  '<!-- Generated by tools/handbuch.mjs from src/lib/handbook.js and src/lib/features.js. Do not edit by hand: run `node tools/handbuch.mjs`. -->',
  '',
  '# Pack Generator · Benutzerhandbuch',
  '',
  'Der Pack Generator hilft dir, Touren zu planen, zu packen, unterwegs den Überblick zu behalten, danach zurückzublicken und deine Velos zu pflegen. Er läuft im Browser, auch offline, und speichert alles nur auf deinem Gerät.',
  '',
  'Die App hat fünf Orte: **Heute** (was jetzt wichtig ist), **Touren** (planen, packen, Rückblick), **Material** (Teile, Kleider, Bausteine, Einkauf), **Velos** (Übersicht, Pflege, Werkstatt, Ausstattung) und **Aktiv** (Aktivitäten, Ziele, Meditation). Dazu kommt **Ich** mit Daten, Eingang, Notizen und Einstellungen.',
  '',
  'Alles in der App ist ein Vorschlag: nichts ist Pflicht, alles lässt sich ändern, abwählen oder ausschalten.',
  '',
  `Pro Funktion steht hier: was sie tut, wie du sie aufschaltest, die Schritte und ein Beispiel. Alle ${FEATURES.length} Funktionen findest du auch in der App unter Ich › Was die App alles kann.`,
  '',
  `## ${de(MINI_APPS_HANDBOOK.title)}`,
  '',
  MINI_APPS_HANDBOOK.intro.map(de).join(' '),
  '',
];
for (const a of MINI_APPS_HANDBOOK.apps) {
  out.push(`### ${de(a.title)}`, '', ...steps(a.steps), '', `**Beispiel:** ${example(a.example)}`, '');
}
for (const g of FEATURE_GROUPS) {
  out.push(`## ${de(g.label)}`, '');
  for (const f of FEATURES.filter((x) => x.group === g.key)) {
    const h = HANDBOOK[f.id];
    out.push(
      `### ${de(f.title)}`,
      '',
      de(f.text),
      '',
      `**Aufschalten:** ${h.on ? de(h.on) : 'Immer da, nichts zu tun.'}`,
      '',
      ...steps(h.steps),
      '',
      `**Beispiel:** ${example(h.example)}`,
      '',
    );
  }
}
out.push('## Bezahlen', '', 'Die Bezahlfunktion ist vorbereitet und noch unsichtbar, siehe [docs/bezahlen.md](bezahlen.md).', '');

const file = fileURLToPath(new URL('../docs/handbuch.md', import.meta.url));
writeFileSync(file, out.join('\n'));
console.log(`docs/handbuch.md: ${FEATURES.length} functions, ${MINI_APPS_HANDBOOK.apps.length} small apps`);
