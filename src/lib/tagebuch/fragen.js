/** Day of the year 0 … 365 for YYYY-MM-DD (calendar days, no clock involved). */
export function dayOfYear(day) {
  const [y, m, d] = String(day).split('-').map(Number);
  return Math.round((Date.UTC(y, m - 1, d) - Date.UTC(y, 0, 1)) / 864e5);
}

/** The question of `day` (index into QUESTIONS); `skip` steps further with «Other question». */
export function questionOf(day, skip = 0, n = QUESTIONS.length) {
  const i = Number.isFinite(dayOfYear(day)) ? dayOfYear(day) : 0;
  return (((i + skip * 37) % n) + n) % n;
}
